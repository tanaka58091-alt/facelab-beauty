export function getKnowledgeFor(problemKeys){
  const cards = [];
  const seen = new Set();
  problemKeys.forEach(k => {
    (KNOWLEDGE[k] || []).forEach(c => {
      const key = c.title;
      if (seen.has(key)) return;
      seen.add(key);
      cards.push(c);
    });
  });
  // 共通カードを末尾に
  COMMON.forEach(c => {
    if (!seen.has(c.title)) cards.push(c);
  });
  return cards.slice(0, 6);
}
